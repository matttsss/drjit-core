/**
 * pack.c: Pack precompiled kernel PTX for redistribution
 *
 * Dr.Jit's builtin PTX files are quite large (~3.6MB uncompressed).
 * Compiling the entire PTX blob via the CUDA driver's JIT takes several seconds
 * (cold), even though a typical program only touches a handful of the ~650
 * kernels. To enable lazy, per-kernel JIT compilation at runtime, this tool
 * rewrites the monolithic PTX into a self-describing blob:
 *
 *     [ preamble ]\0[ entry 0 ]\0[ entry 1 ]\0 ... [ entry N-1 ]\0
 *
 * The preamble holds the module header (``.version`` / ``.target`` /
 * ``.address_size`` and the two ``.extern .shared`` declarations). Each entry
 * is one complete, self-contained ``.entry`` definition (the kernels contain no
 * cross-function ``.func`` calls or module-scope data, so an entry prefixed
 * with the preamble is a valid standalone PTX module). ``kernels_75_offsets[]``
 * gives the byte offset of each entry within the decompressed blob, parallel to
 * the kernel names in ``kernels_list``.
 * The blob is then LZ4-compressed. No dictionary is used: LZ4 can only
 * reference it from the first 64 KiB of a multi-megabyte blob.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <lz4hc.h>

char *read_file(const char *fname, size_t *size_out) {
    FILE *f = fopen(fname, "r");
    if (!f) {
        fprintf(stderr, "Could not open '%s'!\n", fname);
        exit(EXIT_FAILURE);
    }

    fseek(f, 0, SEEK_END);
    size_t size = ftell(f);
    char *buf = malloc(size + 1);
    buf[size] = '\0';
    fseek(f, 0, SEEK_SET);

    if (fread(buf, size, 1, f) != 1) {
        fprintf(stderr, "Could not read '%s'!\n", fname);
        exit(EXIT_FAILURE);
    }

    fclose(f);
    *size_out = size;
    return buf;
}

/// LZ4-compress an in-memory buffer, write it to ``dst_fname``, and emit the
/// ``extern`` symbol declaration and size constants to ``f``.
void pack_buffer(FILE *f, const char *id, const void *source, size_t source_size,
                 const char *dst_fname) {
    int buf_size = LZ4_compressBound(source_size);
    char *buf = (char *) malloc(buf_size);

    size_t compressed_size = LZ4_compress_HC(source, buf, source_size, buf_size,
                                             LZ4HC_CLEVEL_MAX);

    fprintf(f, "extern const char %s[];\n", id);
    fprintf(f, "static const size_t %s_size_uncompressed = %zu;\n", id, source_size);
    fprintf(f, "static const size_t %s_size_compressed = %zu;\n", id, compressed_size);

    FILE *f2 = fopen(dst_fname, "wb");
    if (!f2) {
        fprintf(stderr, "Could not open '%s'!", dst_fname);
        exit(EXIT_FAILURE);
    }
    fwrite(buf, 1, compressed_size, f2);
    fclose(f2);
    free(buf);
    fprintf(f, "\n");
}

/// Return the offset of the beginning of the line containing ``pos``
static size_t line_start(const char *base, const char *pos) {
    while (pos > base && pos[-1] != '\n')
        --pos;
    return (size_t) (pos - base);
}

/// Create a generated header and write its prologue
static FILE *open_header(const char *fname) {
    FILE *f = fopen(fname, "w");
    if (!f) {
        fprintf(stderr, "Could not open '%s'!", fname);
        exit(EXIT_FAILURE);
    }

    fprintf(f, "// This file was automatically generated by \"pack\"\n\n");
    fprintf(f, "#pragma once\n\n");
    fprintf(f, "#include <stdlib.h>\n\n");
    fprintf(f, "#if defined(__GNUC__)\n");
    fprintf(f, "#  pragma GCC diagnostic push\n");
    fprintf(f, "#  pragma GCC diagnostic ignored \"-Wunused-variable\"\n");
    fprintf(f, "#endif\n\n");

    fprintf(f, "#ifdef __cplusplus\n");
    fprintf(f, "extern \"C\" {\n");
    fprintf(f, "#endif\n\n");

    return f;
}

static void close_header(FILE *f) {
    fprintf(f, "#ifdef __cplusplus\n");
    fprintf(f, "}\n");
    fprintf(f, "#endif\n\n");

    fprintf(f, "#if defined(__GNUC__)\n");
    fprintf(f, "#  pragma GCC diagnostic pop\n");
    fprintf(f, "#endif\n\n");

    fclose(f);
}

/// Split and compress the CUDA PTX kernels (see the file comment)
static void pack_ptx(void) {
    FILE *f = open_header("kernels.h");

    size_t ptx_size;
    char *ptx = read_file("kernels_75.ptx", &ptx_size);

    // Locate the line-start of every '.entry' definition (each '.entry ' match
    // lies mid-line, after an optional '.visible ' qualifier).
    size_t capacity = 1024, count = 0;
    size_t *entry_pos = malloc(capacity * sizeof(size_t));
    for (char *p = strstr(ptx, ".entry "); p; p = strstr(p + 7, ".entry ")) {
        if (count == capacity) {
            capacity *= 2;
            entry_pos = realloc(entry_pos, capacity * sizeof(size_t));
        }
        entry_pos[count++] = line_start(ptx, p);
    }
    if (count == 0) {
        fprintf(stderr, "pack: no '.entry' definitions found in kernels_75.ptx!\n");
        exit(EXIT_FAILURE);
    }

    size_t preamble_size = entry_pos[0];

    // Assemble the blob: preamble + each entry, all '\0'-terminated.
    char *blob = malloc(ptx_size + count + 2);
    size_t *offsets = malloc(count * sizeof(size_t));
    size_t pos = 0;

    memcpy(blob, ptx, preamble_size);
    pos = preamble_size;
    blob[pos++] = '\0';

    for (size_t i = 0; i < count; ++i) {
        size_t begin = entry_pos[i];
        size_t end   = (i + 1 < count) ? entry_pos[i + 1] : ptx_size;
        offsets[i] = pos;
        memcpy(blob + pos, ptx + begin, end - begin);
        pos += end - begin;
        blob[pos++] = '\0';
    }

    pack_buffer(f, "kernels_75", blob, pos, "kernels_75.lz4");

    fprintf(f, "static const size_t kernels_75_preamble_size = %zu;\n\n",
            preamble_size);

    // Offset of each entry's self-contained PTX within the decompressed blob,
    // parallel to the names in 'kernels_list' below.
    fprintf(f, "static const unsigned int kernels_75_offsets[] = {");
    for (size_t i = 0; i < count; ++i)
        fprintf(f, "%s%u,", (i % 8 == 0) ? "\n    " : " ",
                (unsigned int) offsets[i]);
    fprintf(f, "\n};\n\n");

    // Kernel names, in the same order as 'kernels_75_offsets'.
    fprintf(f, "static const char *kernels_list =");
    for (size_t i = 0; i < count; ++i) {
        char *name = ptx + entry_pos[i];
        name = strstr(name, ".entry ") + 7;
        char *next = strchr(name, '(');
        fprintf(f, "\n    \"");
        fwrite(name, next - name, 1, f);
        fprintf(f, ",\"");
    }
    fprintf(f, ";\n\n");

    free(entry_pos);
    free(offsets);
    free(blob);
    free(ptx);
    close_header(f);
}

/// Compress the precompiled Metal utility kernel library
static void pack_metal(void) {
    FILE *f = open_header("metal_kernels.h");

    size_t size;
    char *data = read_file("metal_kernels.metallib", &size);
    pack_buffer(f, "metal_kernels", data, size, "metal_kernels.lz4");
    free(data);
    close_header(f);
}

struct VulkanKernelSpec {
    char name[64];
    char flags[160];
};

static void add_vulkan_kernel(struct VulkanKernelSpec **list, size_t *count,
                              size_t *cap, const char *name, const char *flags) {
    if (*count == *cap) {
        *cap = *cap ? (*cap * 2) : 256;
        *list = realloc(*list, *cap * sizeof(struct VulkanKernelSpec));
    }
    snprintf((*list)[*count].name, sizeof((*list)[*count].name), "%s", name);
    snprintf((*list)[*count].flags, sizeof((*list)[*count].flags), "%s", flags);
    (*count)++;
}

/// Compile and compress the Vulkan utility kernels from vulkan_kernels.glsl
static void pack_vulkan(void) {
    struct VulkanKernelSpec *specs = NULL;
    size_t count = 0, cap = 0;

    add_vulkan_kernel(&specs, &count, &cap, "compress_scatter",
                      "-DKERNEL_COMPRESS_SCATTER");
    add_vulkan_kernel(&specs, &count, &cap, "mkperm_phase_1",
                      "-DKERNEL_MKPERM_PHASE_1");
    add_vulkan_kernel(&specs, &count, &cap, "mkperm_phase_3",
                      "-DKERNEL_MKPERM_PHASE_3");
    add_vulkan_kernel(&specs, &count, &cap, "mkperm_detect_offsets",
                      "-DKERNEL_MKPERM_DETECT_OFFSETS");
    add_vulkan_kernel(&specs, &count, &cap, "mkperm_phase_1_tiny",
                      "-DKERNEL_MKPERM_PHASE_1_TINY");
    add_vulkan_kernel(&specs, &count, &cap, "mkperm_phase_4_tiny",
                      "-DKERNEL_MKPERM_PHASE_4_TINY");

    static const struct {
        const char *op;
        const char *op_def;
        const char *types[8];
        const char *type_defs[8];
    } red_table[] = {
        { "add", "OP_ADD",
          { "f16", "f32", "f64", "u32", "u64", NULL },
          { "TYPE_F16", "TYPE_F32", "TYPE_F64", "TYPE_U32", "TYPE_U64", NULL } },
        { "mul", "OP_MUL",
          { "f16", "f32", "f64", "u32", "u64", NULL },
          { "TYPE_F16", "TYPE_F32", "TYPE_F64", "TYPE_U32", "TYPE_U64", NULL } },
        { "min", "OP_MIN",
          { "f16", "f32", "f64", "u32", "u64", "i32", "i64", NULL },
          { "TYPE_F16", "TYPE_F32", "TYPE_F64", "TYPE_U32", "TYPE_U64", "TYPE_I32", "TYPE_I64", NULL } },
        { "max", "OP_MAX",
          { "f16", "f32", "f64", "u32", "u64", "i32", "i64", NULL },
          { "TYPE_F16", "TYPE_F32", "TYPE_F64", "TYPE_U32", "TYPE_U64", "TYPE_I32", "TYPE_I64", NULL } },
        { "or", "OP_OR",
          { "u8", "u32", "u64", NULL },
          { "TYPE_U8", "TYPE_U32", "TYPE_U64", NULL } },
        { "and", "OP_AND",
          { "u8", "u32", "u64", NULL },
          { "TYPE_U8", "TYPE_U32", "TYPE_U64", NULL } }
    };

    for (size_t i = 0; i < sizeof(red_table) / sizeof(red_table[0]); ++i) {
        for (size_t j = 0; red_table[i].types[j]; ++j) {
            const char *op = red_table[i].op;
            const char *op_def = red_table[i].op_def;
            const char *tn = red_table[i].types[j];
            const char *td = red_table[i].type_defs[j];
            char name[64], flags[160];

            snprintf(name, sizeof(name), "block_reduce_small_%s_%s", op, tn);
            snprintf(flags, sizeof(flags),
                     "-DKERNEL_BLOCK_REDUCE_SMALL -D%s -D%s", op_def, td);
            add_vulkan_kernel(&specs, &count, &cap, name, flags);

            snprintf(name, sizeof(name), "block_reduce_%s_%s", op, tn);
            snprintf(flags, sizeof(flags),
                     "-DKERNEL_BLOCK_REDUCE_CHUNK -D%s -D%s", op_def, td);
            add_vulkan_kernel(&specs, &count, &cap, name, flags);

            // block_prefix_reduce skips u8 for or/and
            if (strcmp(tn, "u8") != 0) {
                snprintf(name, sizeof(name), "block_prefix_reduce_small_%s_%s", op, tn);
                snprintf(flags, sizeof(flags),
                         "-DKERNEL_BLOCK_PREFIX_REDUCE_SMALL -D%s -D%s", op_def, td);
                add_vulkan_kernel(&specs, &count, &cap, name, flags);

                snprintf(name, sizeof(name), "block_prefix_reduce_%s_%s", op, tn);
                snprintf(flags, sizeof(flags),
                         "-DKERNEL_BLOCK_PREFIX_REDUCE -D%s -D%s", op_def, td);
                add_vulkan_kernel(&specs, &count, &cap, name, flags);
            }
        }
    }

    // Widened chunk reductions & u8 -> u32 prefix scan (for f16 prefix scan & compress)
    add_vulkan_kernel(&specs, &count, &cap, "block_reduce_wide_add_f16",
                      "-DKERNEL_BLOCK_REDUCE_CHUNK -DOP_ADD -DTYPE_F16 -DWIDE_OUT");
    add_vulkan_kernel(&specs, &count, &cap, "block_reduce_wide_mul_f16",
                      "-DKERNEL_BLOCK_REDUCE_CHUNK -DOP_MUL -DTYPE_F16 -DWIDE_OUT");
    add_vulkan_kernel(&specs, &count, &cap, "block_reduce_wide_add_u8",
                      "-DKERNEL_BLOCK_REDUCE_CHUNK -DOP_ADD -DTYPE_U8 -DWIDE_OUT");
    add_vulkan_kernel(&specs, &count, &cap, "block_prefix_reduce_small_add_u8",
                      "-DKERNEL_BLOCK_PREFIX_REDUCE_SMALL -DOP_ADD -DTYPE_U8 -DWIDE_OUT");
    add_vulkan_kernel(&specs, &count, &cap, "block_prefix_reduce_add_u8",
                      "-DKERNEL_BLOCK_PREFIX_REDUCE -DOP_ADD -DTYPE_U8 -DWIDE_OUT");

    // Fused dot-product reductions
    add_vulkan_kernel(&specs, &count, &cap, "reduce_dot_f16",
                      "-DKERNEL_REDUCE_DOT -DTYPE_F16");
    add_vulkan_kernel(&specs, &count, &cap, "reduce_dot_f32",
                      "-DKERNEL_REDUCE_DOT -DTYPE_F32");
    add_vulkan_kernel(&specs, &count, &cap, "reduce_dot_f64",
                      "-DKERNEL_REDUCE_DOT -DTYPE_F64");

    size_t blob_cap = 512 * 1024, blob_pos = 0;
    char *blob = malloc(blob_cap);
    size_t *offsets = malloc(count * sizeof(size_t));
    size_t *sizes   = malloc(count * sizeof(size_t));

    const char *tmp_spv = "vulkan_kernel_tmp.spv";
    for (size_t i = 0; i < count; ++i) {
        char cmd[512];
        snprintf(cmd, sizeof(cmd),
                 "glslangValidator --quiet -V --target-env vulkan1.3 -S comp %s "
                 "vulkan_kernels.glsl -o %s",
                 specs[i].flags, tmp_spv);
        int ret = system(cmd);
        if (ret != 0) {
            fprintf(stderr, "pack: glslangValidator failed for '%s'!\n",
                    specs[i].name);
            remove(tmp_spv);
            exit(EXIT_FAILURE);
        }

        size_t spv_size = 0;
        char *spv = read_file(tmp_spv, &spv_size);
        if (spv_size == 0 || (spv_size % 4) != 0) {
            fprintf(stderr, "pack: invalid SPIR-V size (%zu) for '%s'!\n",
                    spv_size, specs[i].name);
            remove(tmp_spv);
            exit(EXIT_FAILURE);
        }

        if (blob_pos + spv_size > blob_cap) {
            while (blob_pos + spv_size > blob_cap)
                blob_cap *= 2;
            blob = realloc(blob, blob_cap);
        }

        offsets[i] = blob_pos;
        sizes[i]   = spv_size;
        memcpy(blob + blob_pos, spv, spv_size);
        blob_pos += spv_size;
        free(spv);
    }
    remove(tmp_spv);

    FILE *f = open_header("vulkan_kernels.h");
    pack_buffer(f, "vulkan_kernels", blob, blob_pos, "vulkan_kernels.lz4");

    fprintf(f, "static const unsigned int vulkan_kernels_offsets[] = {");
    for (size_t i = 0; i < count; ++i)
        fprintf(f, "%s%u,", (i % 8 == 0) ? "\n    " : " ",
                (unsigned int) offsets[i]);
    fprintf(f, "\n};\n\n");

    fprintf(f, "static const unsigned int vulkan_kernels_sizes[] = {");
    for (size_t i = 0; i < count; ++i)
        fprintf(f, "%s%u,", (i % 8 == 0) ? "\n    " : " ",
                (unsigned int) sizes[i]);
    fprintf(f, "\n};\n\n");

    fprintf(f, "static const char *vulkan_kernels_list =");
    for (size_t i = 0; i < count; ++i)
        fprintf(f, "\n    \"%s,\"", specs[i].name);
    fprintf(f, ";\n\n");

    free(specs);
    free(offsets);
    free(sizes);
    free(blob);
    close_header(f);
}

int main(int argc, char **argv) {
    if (argc > 1 && strcmp(argv[1], "metal") == 0)
        pack_metal();
    else if (argc > 1 && strcmp(argv[1], "vulkan") == 0)
        pack_vulkan();
    else
        pack_ptx();

    return EXIT_SUCCESS;
}
